describe("CR 407.7 / 407.8 — ownership", () => {
  rule(["CR 407.7", "CR 407.7a"], "every card of a player's deck, their faction card included, is owned by that player", () => {
    const filler = (i: number) => character({ name: `Filler ${i}`, id: `r04-own-f-${i}` });
    const facA = factionCard({ name: "Faction A", id: "r04-own-fa", faction: defaultFactionDefinition() });
    const facB = factionCard({ name: "Faction B", id: "r04-own-fb", faction: defaultFactionDefinition() });
    const fillersA = Array.from({ length: 10 }, (_, i) => filler(i));
    const fillersB = Array.from({ length: 10 }, (_, i) => filler(100 + i));
    const defs: CardDefinition[] = [facA, facB, ...fillersA, ...fillersB];
    const engine = createFactionGame(
      defs,
      [{ id: P1, name: "A", deckDefinitionIds: [facA.id, ...fillersA.map((d) => d.id)] },
      { id: P2, name: "B", deckDefinitionIds: [facB.id, ...fillersB.map((d) => d.id)] }],
      { firstPlayerId: P1, seed: 7 }
    );
    const owners = (player: PlayerId, ids: string[]) =>
      Object.values(engine.state.cards)
        .filter((card) => ids.includes(card.definitionId))
        .map((card) => card.ownerId === player);
    const aIds = [facA.id, ...fillersA.map((d) => d.id)];
    const bIds = [facB.id, ...fillersB.map((d) => d.id)];
    assert.equal(owners(P1, aIds).length, 11, "all 11 of the first deck's cards exist");
    assert.ok(owners(P1, aIds).every(Boolean), "the first player owns every card of their deck");
    assert.ok(owners(P2, bIds).every(Boolean), "the second player owns every card of their deck");
    const faction = engine.state.cards[engine.state.players[P1].factionId!]!;
    assert.equal(faction.ownerId, P1, "including the faction card");
    assert.equal(faction.controllerId, P1, "which they also control");
  });

  rule("CR 407.7", "you still own a card another player controls: ownership selectors and the owner's piles follow the owner", () => {
    const { engine, id } = buildGame({
      cards: [
        { key: "thief", def: stealer("Thief", OPP_CHARACTER), owner: P1 },
        { key: "victim", def: character({ name: "Victim" }), owner: P2 }
      ]
    });
    activate(engine, P1, id("thief"), "steal", id("victim"));
    const owned = (player: PlayerId, controller: "self" | "opponent") =>
      engine.queryCards({ owner: "self", controller }, { sourceId: id("thief"), controllerId: player, selected: {} }).map((card) => card.id);
    assert.ok(owned(P2, "opponent").includes(id("victim")), "P2 still owns it, though the opponent controls it");
    assert.ok(!owned(P1, "self").includes(id("victim")), "P1 controls it but does not own it");
    engine.resolveEffect({ type: "destroy", target: REF(id("victim")) }, ctx(id("thief")));
    assert.ok(engine.state.players[P2].discard.includes(id("victim")), "destroyed, it goes to its owner's discard pile");
    assert.ok(!engine.state.players[P1].discard.includes(id("victim")), "not the controller's");
  });

  rule("CR 407.8", "ownership never changes: through theft, a return and a hand/deck of the other player, the owner stays the owner", () => {
    const { engine, id } = buildGame({
      cards: [
        { key: "thief", def: stealer("Thief", OPP_CHARACTER), owner: P1 },
        { key: "counter", def: stealer("Counter", OPP_CHARACTER), owner: P2 },
        { key: "victim", def: character({ name: "Victim" }), owner: P2 }
      ]
    });
    const owner = () => ownerOf(engine, id("victim"));
    activate(engine, P1, id("thief"), "steal", id("victim"));
    assert.equal(owner(), P2, "after theft");
    passTurn(engine);
    activate(engine, P2, id("counter"), "steal", id("victim"));
    assert.equal(owner(), P2, "after the steal back");
    engine.resolveEffect({ type: "takeControl", target: REF(id("victim")), controller: "opponent" }, ctx(id("thief"), P2));
    assert.equal(controllerOf(engine, id("victim")), P1, "control moved again");
    assert.equal(owner(), P2, "after another control change");
    engine.resolveEffect({ type: "moveCard", target: REF(id("victim")), to: "hand", toPlayer: "controller" }, ctx(id("thief"), P1));
    assert.ok(engine.state.players[P1].hand.includes(id("victim")), "it is in my hand");
    assert.equal(owner(), P2, "even in the other player's hand");
    engine.resolveEffect({ type: "moveCard", target: REF(id("victim")), to: "deck", toPlayer: "controller", position: "top" }, ctx(id("thief"), P1));
    assert.ok(engine.state.players[P1].deck.includes(id("victim")), "it is in my deck");
    assert.equal(owner(), P2, "even in the other player's deck");
    engine.resolveEffect({ type: "moveCard", target: REF(id("victim")), to: "discard" }, ctx(id("thief"), P1));
    assert.equal(owner(), P2, "after going to the discard pile");
    assert.ok(engine.state.players[P2].discard.includes(id("victim")), "which is its owner's");
  });
});
