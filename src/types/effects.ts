// -----------------------------------------------------------------------------
// Effects
// -----------------------------------------------------------------------------

import type { Duration, ModifierOperation, Stat, Zone } from "./ids.js";
import type { NumberExpression, PlayerRef, TargetRef } from "./expressions.js";

export type Effect =
  | {
      type: "draw";
      player: PlayerRef;
      amount: NumberExpression;
    }
  | {
      /**
       * Play a selected card as a resource. "auto" plays actual resource
       * cards face-up and all other cards face-down.
       */
      type: "playResource";
      target: TargetRef;
      faceDown: boolean | "auto";
    }
  | {
      type: "dealDamage";
      target: TargetRef;
      amount: NumberExpression;
    }
  | {
      type: "modifyInfluence";
      player: PlayerRef;
      amount: NumberExpression;
    }
  | {
      type: "moveCard";
      target: TargetRef;
      to: Zone;
    }
  | {
      type: "destroy";
      target: TargetRef;
    }
  | {
      type: "deplete";
      target: TargetRef;
    }
  | {
      type: "restore";
      target: TargetRef;
    }
  | {
      type: "addCounter";
      target: TargetRef;
      counter: string;
      amount: NumberExpression;
    }
  | {
      type: "removeCounter";
      target: TargetRef;
      counter: string;
      amount: NumberExpression;
    }
  | {
      type: "createModifier";
      target: TargetRef;
      stat: Stat;
      operation: ModifierOperation;
      value: NumberExpression;
      duration: Duration;
    };

export interface ModifierDefinition {
  target: TargetRef;
  stat: Stat;
  operation: ModifierOperation;
  value: NumberExpression;
}
