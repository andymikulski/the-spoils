// sync-cards.cjs
//
// data/sets.json + data/cards/<set id>.json are the source of truth for card
// data (see scripts/lib/catalog.cjs). This script regenerates the ES modules
// the package ships from them; copying only ever goes one way. Never hand-edit
// anything it writes:
//
//   src/data/sets/<set id>.js  one set's printings (the "./sets/*" export)
//   src/data/cards.js          every set, concatenated in data/sets.json order
//                              (default), and each set by name (CARDS_<ID>)
//   src/data/set-index.js      each set's id, name and card count
//   src/data/card-fidelity.js  mirror of data/card-fidelity.json (generated
//                              by scripts/build-coverage.cjs)
//
// The modules carry JSDoc types, so tsc emits typed declarations for them.

const fs = require("node:fs");
const path = require("node:path");
const { ROOT, loadCatalog } = require("./lib/catalog.cjs");

const DATA_DIR = path.join(ROOT, "data");
const OUT_DIR = path.join(ROOT, "src", "data");
const SETS_OUT = path.join(OUT_DIR, "sets");

const header = (source) => `// Generated by scripts/sync-cards.cjs from ${source}. Do not edit.\n`;

function writeIfChanged(file, text) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === text) return false;
  fs.writeFileSync(file, text);
  return true;
}

const { sets, cards } = loadCatalog();
fs.mkdirSync(SETS_OUT, { recursive: true });

let changed = 0;
for (const set of sets) {
  const text =
    header(`data/cards/${set.id}.json`) +
    `/** @type {import("../../types/index.js").CardDefinition[]} */\n` +
    `const cards = ${JSON.stringify(set.cards, null, 2)};\n` +
    `export default cards;\n`;
  if (writeIfChanged(path.join(SETS_OUT, `${set.id}.js`), text)) changed++;
}
const live = new Set(sets.map((set) => `${set.id}.js`));
for (const file of fs.readdirSync(SETS_OUT)) {
  if (!live.has(file)) {
    fs.rmSync(path.join(SETS_OUT, file));
    console.log(`Removed src/data/sets/${file} (no longer in data/sets.json)`);
  }
}

// Each set is also a named export (re-exported by the-spoils/data):
// "seed-saga" -> CARDS_SEED_SAGA.
const exportName = (set) => `CARDS_${set.id.toUpperCase().replace(/-/g, "_")}`;
writeIfChanged(
  path.join(OUT_DIR, "cards.js"),
  header("data/sets.json") +
    sets.map((set) => `import ${exportName(set)} from "./sets/${set.id}.js";\n`).join("") +
    `\nexport {\n${sets.map((set) => `  ${exportName(set)}`).join(",\n")}\n};\n` +
    `\n/** @type {import("../types/index.js").CardDefinition[]} */\n` +
    `const cards = [${sets.map((set) => `...${exportName(set)}`).join(", ")}];\n` +
    `export default cards;\n`
);

const index = sets.map((set) => ({ id: set.id, name: set.name, cardCount: set.cards.length }));
writeIfChanged(
  path.join(OUT_DIR, "set-index.js"),
  header("data/sets.json") +
    `/** @type {readonly import("../sets.js").CardSetInfo[]} */\n` +
    `const sets = ${JSON.stringify(index, null, 2)};\n` +
    `export default sets;\n`
);
console.log(`Synced ${cards.length} cards in ${sets.length} sets -> src/data/ (${changed} set module(s) changed)`);

const fidelityPath = path.join(DATA_DIR, "card-fidelity.json");
if (fs.existsSync(fidelityPath)) {
  const fidelity = JSON.parse(fs.readFileSync(fidelityPath, "utf8"));
  writeIfChanged(path.join(OUT_DIR, "card-fidelity.js"), `export default ${JSON.stringify(fidelity, null, 2)}\n`);
  console.log(`Synced fidelity (${Object.keys(fidelity.fidelity).length} cards) -> src/data/card-fidelity.js`);
}
