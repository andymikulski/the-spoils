#!/usr/bin/env node
// Regenerates CARD-TEST-PROGRESS.md — the tracker for the per-card
// correctness suite (src/engine/__tests__/per-card/<set>.test.ts).
//
// "Done" = the set's per-card test file mentions the card name literally
// (in a describe()/test() title or a driver array). Deliberately loose: the
// point is a running tally, not a contract. Re-run after adding tests:
//
//   node scripts/build-card-test-progress.cjs
//
// Pass --check to fail (exit 1) if the committed file is stale (CI helper).

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "CARD-TEST-PROGRESS.md");
const PER_CARD_DIR = path.join(ROOT, "src/engine/__tests__/per-card");

const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, "data/cards.json"), "utf8"));

// Rollout order (smallest set first) — matches COVERAGE.md.
const SET_ORDER = [
  "Seed 3",
  "Seed 2",
  "Shade of the Devoured Emperor",
  "1st Edition Part 2",
  "Holy Heist",
  "Ungodly Mess",
  "Open Beta",
  "1st Edition",
  "Seed",
  "2nd Edition",
  "Seed Saga"
];

const slug = set =>
  set
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

function testedNames(set) {
  const file = path.join(PER_CARD_DIR, `${slug(set)}.test.ts`);
  if (!fs.existsSync(file)) return new Set();
  const src = fs.readFileSync(file, "utf8");
  const tested = new Set();
  for (const card of catalog) {
    if (card.set !== set) continue;
    // The card name appears verbatim, immediately preceded by a quote,
    // backtick, or the "— " of a describe() title, and followed by a quote,
    // backtick, comma, or period (so "Rage" doesn't match "Outrageous").
    const esc = card.name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const re = new RegExp(`(["'\`]|— )${esc}(["'\`,.]|$)`, "m");
    if (re.test(src)) tested.add(card.name);
  }
  return tested;
}

const sets = SET_ORDER.filter(s => catalog.some(c => c.set === s));
for (const s of new Set(catalog.map(c => c.set))) {
  if (!sets.includes(s)) sets.push(s);
}

let totalCards = 0;
let totalDone = 0;
const perSet = [];

for (const set of sets) {
  const cards = catalog.filter(c => c.set === set).sort((a, b) => a.name.localeCompare(b.name));
  const done = testedNames(set);
  totalCards += cards.length;
  totalDone += done.size;
  perSet.push({ set, cards, done });
}

const lines = [];
lines.push("# CARD-TEST-PROGRESS.md");
lines.push("");
lines.push(
  "**Generated by `scripts/build-card-test-progress.cjs` — do not hand-edit.**"
);
lines.push("");
lines.push(
  "Tracker for the per-card correctness suite: `src/engine/__tests__/per-card/<set>.test.ts`."
);
lines.push(
  "Each set file has one `describe()` per catalog card that seeds a tiny mid-game"
);
lines.push(
  "board, takes a turn, triggers/activates/plays the card with concrete picks, and"
);
lines.push(
  "asserts the concrete outcome **and** target legality. See `per-card/_harness.ts`."
);
lines.push("");
lines.push(
  "A card is counted **done** when its set file has a `describe()` naming it."
);
lines.push("");
lines.push(`**Overall: ${totalDone} / ${totalCards} cards.**`);
lines.push("");
lines.push("| Set | Cards | Done | Remaining | % |");
lines.push("|---|--:|--:|--:|--:|");
for (const { set, cards, done } of perSet) {
  const pct = cards.length ? Math.round((done.size / cards.length) * 100) : 100;
  lines.push(
    `| ${set} | ${cards.length} | ${done.size} | ${cards.length - done.size} | ${pct}% |`
  );
}
lines.push("");

for (const { set, cards, done } of perSet) {
  lines.push(`## ${set} — ${done.size} / ${cards.length}`);
  lines.push("");
  lines.push(`Test file: \`src/engine/__tests__/per-card/${slug(set)}.test.ts\``);
  lines.push("");
  for (const card of cards) {
    lines.push(`- [${done.has(card.name) ? "x" : " "}] ${card.name} _(${card.type})_`);
  }
  lines.push("");
}

const rendered = lines.join("\n") + "\n";

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== rendered) {
    console.error("CARD-TEST-PROGRESS.md is stale — run: node scripts/build-card-test-progress.cjs");
    process.exit(1);
  }
  console.log("CARD-TEST-PROGRESS.md is up to date.");
} else {
  fs.writeFileSync(OUT, rendered);
  console.log(`Wrote ${OUT} — ${totalDone}/${totalCards} cards done.`);
}
